#!/usr/bin/env node
// Writes docs/MI_DATA_STATUS.md from the county files in data/real/ and the last
// `f65-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { F65_PAGE, F65_YEARS } from './f65-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'mi', 'f65-report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^mi-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities', Village: 'Villages', 'Charter Township': 'Charter Townships', Township: 'Townships' };
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  const years = [...new Set(g.map((t) => t.fiscalYear))].sort();
  const fy = years.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
  return { kind, n: g.length, fy, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');

writeFileSync(join(ROOT, 'docs', 'MI_DATA_STATUS.md'), `# Michigan data status

Generated by \`node scripts/mi/f65-status.mjs\`. ${towns.length} governments loaded. Michigan has 83 counties, about 280 cities, 250 villages and 1,240 townships (general law and charter). Villages are part of the township around them, so village residents pay both; cities are separate from townships. Public schools are run by separate school districts. Each county's file holds the county and the governments whose people mostly live in it.

| Type | Loaded | Fiscal year used (count) | Median score | Median overhead |
|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue, spending and debt:** each unit's F-65 Annual Local Unit Fiscal Report to the Michigan Department of Treasury, from the [MI Community Financial Dashboard](${F65_PAGE}) (its public feature service: expenditure and revenue lines by fund, and long-term debt), fiscal years ${F65_YEARS[0]}-${F65_YEARS.at(-1)}. The latest year in balance is used.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (counties, places and county subdivisions).

## How Michigan differs
- **Functions come from the report.** Spending is reported by function for the general fund, other governmental funds and enterprise funds. Courts, community and economic development, and redevelopment and public housing count as overhead, like general government.
- **Capital outlay** has no function, so enterprise capital counts as utilities and the rest is spread over each unit's other spending in proportion.
- **Left out:** internal service funds and component units (separate authorities such as downtown development authorities), borrowing, transfers, sales of capital assets, depreciation and extraordinary items. Debt service leaves out what was paid with new borrowing not spent on capital (${report.refinanced.length} governments), most likely refinancing.
- **Tax bills:** townships and cities collect school and county taxes but report only their own levy.

## Known gaps
- **Political money is not scored.** Local candidates file campaign finance reports with their county clerk, not with the state.
- **No debt figure (${report.noDebt.length}):** ${list(report.noDebt)}.
- **"Miscellaneous" spending not broken down (${report.unclassified.length}):** ${list(report.unclassified)}.
- **Not filled in (left out, ${report.empty.length}):** ${list(report.empty)}.
- **Revenue and spending more than four times apart (left out, ${report.inconsistent.length}):** ${list(report.inconsistent)}.
- **Earlier year used:** ${list(report.older)}.
- **No Census match (left out, ${report.skipped.length}):** ${list(report.skipped)}.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/MI_DATA_STATUS.md: ${towns.length} governments`);
