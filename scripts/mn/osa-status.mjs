#!/usr/bin/env node
// Writes docs/MN_DATA_STATUS.md from the county files in data/real/ and the last
// `osa-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { OSA_PAGE } from './osa-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'mn', 'osa-report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^mn-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities', Township: 'Townships' };
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  const years = [...new Set(g.map((t) => t.fiscalYear))].sort();
  const fy = years.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
  return { kind, n: g.length, fy, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');

writeFileSync(join(ROOT, 'docs', 'MN_DATA_STATUS.md'), `# Minnesota data status

Generated by \`node scripts/mn/osa-status.mjs\`. ${towns.length} governments loaded. Minnesota has 87 counties, about 850 cities and 1,780 townships (towns). Townships govern the areas outside cities, mostly maintaining township roads; cities are separate from the township around them. Counties run human services, public health and county highways. Public schools are run by separate school districts. Each county's file holds the county and the governments whose people mostly live in it.

| Type | Loaded | Year used (count) | Median score | Median overhead |
|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue, spending and debt:** the financial reporting form each county, city and town files with the Minnesota Office of the State Auditor, as the Auditor publishes it for [counties](${OSA_PAGE.county}) (2023-2024), [cities](${OSA_PAGE.city}) (2022-2023) and [towns](${OSA_PAGE.town}) (2023). The latest year in balance is used.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (counties, places and county subdivisions).

## How Minnesota differs
- **Functions come from the report.** Governmental funds are reported by function (general government, police and sheriff, corrections, fire, ambulance, streets and highways, sanitation, human services, health, libraries, parks, housing and redevelopment, economic development, conservation of natural resources, debt service), current spending and capital outlay alike. Housing and redevelopment, economic development and conservation count as overhead, like general government.
- **Enterprise funds on the same footing.** Water, sewer, electric, liquor store, ambulance and other enterprise funds count their operating revenue and expenses with depreciation left out and capital outlay counted when paid, plus debt payments. Principal repaid with new borrowing that was not spent on capital is treated as refinancing (${report.refinanced.length} governments).
- **Borrowing and transfers are left out**, as is principal of bonds refunded with new bonds.
- **County auditors and treasurers collect property tax** for every government, so city and township reports show only their own levy.

## Known gaps
- **Political money is not scored.** Local and county candidates file campaign finance reports locally, not with the state Campaign Finance Board.
- **"All other" spending not broken down (${report.unclassified.length}):** ${list(report.unclassified)}. More than 15% of their spending was reported without a function, so they are not scored on services or overhead.
- **Not filled in (left out, ${report.empty.length}):** ${list(report.empty)}.
- **Revenue and spending more than four times apart (left out, ${report.inconsistent.length}):** ${list(report.inconsistent)}.
- **Earlier year used:** ${list(report.older)}.
- **No Census geography matched (left out, ${report.skipped.length}):** ${list(report.skipped)}; renamed, newly incorporated or reorganized after the 2024 Census geography.
- **Not in the State Auditor's data:** townships that did not file a 2023 report with the State Auditor are not loaded.
- **Cities' latest year is 2023**, the latest the State Auditor has published, while the Census sample has 2024 figures for some larger cities.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/MN_DATA_STATUS.md: ${towns.length} governments`);
