#!/usr/bin/env node
// Writes docs/IA_DATA_STATUS.md from the county files in data/real/ and the last
// `afr-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { DATASETS, DATASET_PAGE, AFR_YEARS } from './afr-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'ia', 'afr-report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^ia-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities' };
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  const years = [...new Set(g.map((t) => t.fiscalYear))].sort();
  const fy = years.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
  return { kind, n: g.length, fy, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');
const link = (id, text) => `[${text}](${DATASET_PAGE(id)})`;

writeFileSync(join(ROOT, 'docs', 'IA_DATA_STATUS.md'), `# Iowa data status

Generated by \`node scripts/ia/afr-status.mjs\`. ${towns.length} governments loaded. Iowa has 99 counties and about 940 cities; every incorporated place is a city, however small. Iowa's townships are not general-purpose governments (their trustees mostly look after cemeteries and contract for fire protection), so none are listed. Public schools are run by separate school districts. Each county's file holds the county and the cities whose people mostly live in it.

| Type | Loaded | Fiscal year used (count) | Median score | Median overhead |
|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue and spending:** each government's Annual Financial Report, as the Iowa Department of Management publishes it on data.iowa.gov: ${link(DATASETS.cityRev, 'city actual revenues')} and ${link(DATASETS.cityExp, 'expenditures')} by line item and fund, ${link(DATASETS.countyRev, 'county actual revenues by type')} and ${link(DATASETS.countyExp, 'expenditures by service area')}, fiscal years ${AFR_YEARS[0]}-${AFR_YEARS.at(-1)} (ending June 30). The latest year in balance is used.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (counties and places).

## How Iowa differs
- **Functions come from the report.** City spending is reported by program (public safety, public works, health and social services, culture and recreation, community and economic development, general government, debt service, business-type and enterprise) and county spending by service area. Community and economic development (including TIF rebates to developers) and county government services to residents count as overhead, like general government.
- **Capital projects** have no program or service area, so they are spread over each government's other spending in proportion; city enterprise capital outlay counts as utilities.
- **Internal service funds** (self-insurance, central garages and the like) are left out, since the departments they serve report that spending.
- **Borrowing, transfers and internal TIF loans are left out.** Debt service leaves out what was paid with new borrowing not spent on capital that year (${report.refinanced.length} governments), most likely refinancing.
- **County treasurers collect property tax** for every government, so city reports show only their own levy.
- **County hospitals** report separately (for example Broadlawns in Polk County), so they are not in county figures.

## Known gaps
- **No debt figure.** Debt outstanding is not in the Department of Management's published data, so debt is not scored.
- **Political money is not scored.** Contributions to city and county candidates were not loaded.
- **Not filled in (left out, ${report.empty.length}):** ${list(report.empty)}.
- **Revenue and spending more than four times apart (left out, ${report.inconsistent.length}):** ${list(report.inconsistent)}.
- **Earlier year used:** ${list(report.older)}.
- **No Census match or not in the data (left out, ${report.skipped.length}):** ${list(report.skipped)}. City of Worthington (Dubuque County) has no report in the published data.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/IA_DATA_STATUS.md: ${towns.length} governments`);
