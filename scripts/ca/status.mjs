#!/usr/bin/env node
// Writes docs/CA_DATA_STATUS.md from the county files in data/real/ and the last
// `sco-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { SCO_YEARS } from './sco-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'ca', 'sco', 'report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^ca-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities', Town: 'Towns' };
const fy = (y) => `${y - 1}-${String(y).slice(2)}`;
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  return {
    kind, n: g.length,
    fy: SCO_YEARS.filter((y) => g.some((t) => t.fiscalYear === y)).map((y) => `${fy(y)}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', '),
    noDebt: g.filter((t) => typeof t.debt !== 'number').length,
    score: Math.round(median(g.map((t) => scoreTown(t).score))),
    admin: Math.round(median(g.map((t) => totals(t).adminShare)) * 100),
  };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');

writeFileSync(join(ROOT, 'docs', 'CA_DATA_STATUS.md'), `# California data status

Generated by \`node scripts/ca/status.mjs\`. ${towns.length} governments loaded. California has 58 counties and about 480 cities and towns. Counties run social services, public health, jails and courts for everyone, and provide city-type services in unincorporated areas. Public schools are run by school districts, and many services come from special districts. San Francisco is a consolidated city and county and is listed once, as a city. Each county's file holds the county and the cities and towns whose people mostly live in it.

| Type | Loaded | Fiscal year used (count) | No debt figures | Median score | Median overhead |
|---|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.noDebt} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue and spending:** each government's Financial Transactions Report to the California State Controller, from [By the Numbers](https://bythenumbers.sco.ca.gov/) (city and county revenues and expenditures by line), fiscal years ${fy(SCO_YEARS[0])} to ${fy(SCO_YEARS.at(-1))}; the latest complete year is used. Every city and county files each year, so nearly all are on ${fy(SCO_YEARS.at(-1))}, where the Census unit files used before had 2022 for most cities.
- **Debt:** the State Controller's raw-data workbooks for ${fy(SCO_YEARS.at(-2))} and ${fy(SCO_YEARS.at(-1))}: principal outstanding on bonds, certificates of participation, other long-term debt, construction financing and leases.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer.

## How California differs
- **Governmental and enterprise funds are both included.** Water, sewer, electric, gas and solid waste utilities count as utilities; airports, harbors and transit as infrastructure; county and city hospitals as health services.
- **Internal service funds are left out**, since their charges are already counted in the departments that pay them, as are depreciation, losses on disposal, transfers between funds and hospitals' intergovernmental transfers (federal match money passed through).
- **Enterprise debt service** is the principal and interest enterprise funds paid on their debt, from the debt forms, in place of the interest expense the enterprise statements show.
- **County capital outlay** is reported by fund rather than by service, so it counts as infrastructure. Cities report capital outlay by service.
- **Courts, prosecutors, public defenders, probation, housing, planning and community development count as overhead**, as in other states.

## Known gaps
- **Political money is not scored.** California county and city candidates file campaign reports with their local filing officer, not with the state.
- **No Census geography matched (left out, ${report.skipped.length}):** ${list(report.skipped.map((s) => s.replace(/: no Census match$/, '')))}.
- **Incomplete in every year (left out, ${report.incomplete.length}):** ${list(report.incomplete)}.
- **Earlier year used** because the latest report was missing or incomplete: ${list(report.older)}.
- **Special districts are separate.** Fire, water, park, library and other districts have their own budgets, so some services residents pay for are not in city or county reports.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/CA_DATA_STATUS.md: ${towns.length} governments`);
