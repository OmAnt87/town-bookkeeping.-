#!/usr/bin/env node
// Writes docs/MA_DATA_STATUS.md from the county files in data/real/.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCSV, slugify } from '../lib.mjs';
import { redFlagLines, filingLines, stateTowns } from '../common/status.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const pop = parseCSV(readFileSync(join(ROOT, 'data', 'raw', 'ma', 'popest.csv'), 'latin1'));
const counties = pop.filter((r) => r.sumlev === '050').map((r) => r.name.replace(/ County$/, '')).sort();
const money = (v) => `$${Math.round(v).toLocaleString('en-US')}`;

const rows = [];
let covered = 0;
const older = [];
const noLevy = [];
for (const county of counties) {
  const file = join(ROOT, 'data', 'real', `ma-${slugify(county)}.json`);
  if (!existsSync(file)) { rows.push(`| ${county} | not started | | | |`); continue; }
  const { towns } = JSON.parse(readFileSync(file, 'utf8'));
  const n = (f) => towns.filter(f).length;
  const types = ['Town', 'City'].map((k) => [k, n((t) => t.type === k)]).filter(([, c]) => c)
    .map(([k, c]) => (k === 'City' ? `${c} ${c === 1 ? 'city' : 'cities'}` : `${c} town${c === 1 ? '' : 's'}`)).join(', ');
  const years = [...new Set(towns.map((t) => t.fiscalYear))].sort();
  older.push(...towns.filter((t) => t.transparency?.auditOnTime === false).map((t) => `${t.name} (FY ${t.fiscalYear})`));
  noLevy.push(...towns.filter((t) => !t.sources.some((s) => /tax levies/.test(s.label))).map((t) => t.name));
  covered += towns.length;
  rows.push(`| ${county} | ${towns.length} (${types}) | ${years.join(', ')} | ${n((t) => typeof t.debt === 'number')} | ${n((t) => t.influence)} |`);
}

const all = stateTowns('MA');
const withPol = all.filter((t) => t.influence);
const polTotal = withPol.reduce((a, t) => a + Object.values(t.influence).reduce((x, y) => x + y, 0), 0);
const since = (all.flatMap((t) => t.sources).find((s) => /Campaign and Political Finance/.test(s.label))?.label.match(/since (\d{4})/) || [])[1] || '';

writeFileSync(join(ROOT, 'docs', 'MA_DATA_STATUS.md'), `# Massachusetts data status

Generated by \`node scripts/ma/status.mjs\`. ${covered} of 351 cities and towns loaded. Most Massachusetts counties no longer have a county government, but files are grouped by the 14 Census counties.

| County | Loaded | Fiscal year(s) | Debt | Political money |
|---|---|---|---|---|
${rows.join('\n')}

## Sources
- **Revenue and spending:** MA Department of Revenue, Division of Local Services (DLS) [Municipal Databank](https://www.mass.gov/info-details/division-of-local-services-municipal-databank): each city and town's Schedule A general-fund revenues and expenditures, as filed after the close of each fiscal year (July 1 to June 30). Actual results, not budgets. History back to FY 2016.
- **Property tax:** DLS certified tax levies by class, for the same fiscal year.
- **Debt:** DLS municipal debt dashboard: total outstanding long-term debt (Schedule A Part 10).
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer.
- **Political money:** MA Office of Campaign and Political Finance ([OCPF](https://www.ocpf.us/)) itemized receipts of candidates for mayor, and for city council where council candidates file with the state, since ${since}.

## How Massachusetts differs
- **Cities and towns run the schools.** Local schools and each town's share of any regional school district are paid from the general fund, so school spending is on each report. It is left out of the services and overhead shares so towns compare with states where school districts are separate governments.
- **State assessments come out of state aid.** "Intergovernmental assessments" (charter school tuition, school choice, transit and county charges) are counted with schools.
- **Fixed costs are reported on their own.** Health insurance, pensions and other benefits (including for school staff) are spread across departments, schools included, in proportion to their size.
- **Taxes include excises.** Schedule A reports all taxes together. The certified property tax levy is shown as property tax and the rest (motor vehicle excise, local-option meals and room excises, penalties and interest) as other taxes and excises. Collections in a year can differ slightly from the levy, so the split is close but not exact.${noLevy.length ? ` No levy was found for: ${noLevy.join(', ')}.` : ''}

## Known gaps
- **Political money covers ${withPol.length} cities** (${money(polTotal)} in all): candidates for mayor, and for city council in the cities whose council candidates file with OCPF. Everyone else running for city or town office, including every town's select board, files with the city or town clerk, so most towns are not scored on political money. Counted: contributions from PACs and from unions and associations. Business and corporate contributions to candidates are banned in Massachusetts. Not counted: individuals, party and candidate committees.
${redFlagLines('MA', all).join('\n')}
${filingLines(all, 'Schedule A annual financial report with DLS').join('\n')}
- **Older year shown** because a newer Schedule A is not filed yet: ${older.length ? older.join(', ') : 'none'}.
- Enterprise funds (often water and sewer), regional school districts, fire and water districts and other separate authorities are not included. Other financing sources (such as bond proceeds) and transfers from a town's own funds are left out because they are not new revenue.
- The statewide report does not separate outside legal and engineering costs from general government, so "consultants" is not broken out.
`);
console.log(`docs/MA_DATA_STATUS.md: ${covered} cities and towns`);
