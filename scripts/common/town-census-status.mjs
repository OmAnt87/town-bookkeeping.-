// Writes docs/<ST>_DATA_STATUS.md for a state built with town-census-build.mjs, from the county
// files in data/real/ and the last `build-county.mjs --all` report. The state script passes
// { code, name, kinds: ['County', 'City', 'Town', ...], text(stats) -> { intro, sources[], differs[], gaps[] } },
// where stats is { towns, members (non-county count), adjusted (count with property tax taken out) }.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { YEARS } from './census-units.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const PLURAL = { County: 'Counties', City: 'Cities' };

export function writeStatus(cfg) {
  const st = cfg.code.toLowerCase();
  const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', st, 'build-report.json'), 'utf8'));
  const towns = readdirSync(OUT).filter((f) => new RegExp(`^${st}-.*\\.json$`).test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
  const rows = cfg.kinds.map((kind) => {
    const g = towns.filter((t) => t.type === kind);
    const fy = YEARS.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
    return { kind, n: g.length, fy, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
  });
  const imputed = [...new Set(report.imputed)].sort();
  const incomplete = [...new Set(report.incomplete)].sort();
  const t = cfg.text({
    towns: towns.length,
    members: towns.filter((x) => x.type !== 'County').length,
    adjusted: towns.filter((x) => x.notes.some((n) => n.includes('own share,'))).length,
  });
  const list = (a) => (a.length ? a.join(', ') : 'none');
  writeFileSync(join(ROOT, 'docs', `${cfg.code}_DATA_STATUS.md`), `# ${cfg.name} data status

Generated by \`node scripts/${st}/status.mjs\`. ${towns.length} governments loaded. ${t.intro}

| Type | Loaded | Fiscal year used (count) | Median score | Median overhead |
|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${PLURAL[r.kind] || `${r.kind}s`} | ${r.n} | ${r.fy} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue, spending and debt:** what each government reported to the U.S. Census Bureau's [Annual Survey of State and Local Government Finances](https://www.census.gov/programs-surveys/gov-finances.html) (individual unit files), FY ${YEARS[0]}-${YEARS.at(-1)}, with the same mapping as the Carolinas and Delaware. The Census counts ${cfg.name}'s towns as township governments. ${YEARS[0]} is a Census of Governments year covering every government; later years cover a sample, so each government's latest reported year is used.${t.sources.map((s) => ` ${s}`).join('')}
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (county subdivisions${cfg.kinds.includes('Village') ? ' and places' : ''}).

## How ${cfg.name} differs
${t.differs.map((d) => `- ${d}`).join('\n')}

## Known gaps
${t.gaps.map((d) => `- ${d}`).join('\n')}
${report.assessments?.length ? `- **School and county assessments filed as town spending (left out, ${report.assessments.length}):** ${list(report.assessments)}. Each of these towns, with no school spending of its own, reported most of its budget as "other general government", which is almost certainly its assessments; that spending is treated as a payment to other governments, and the town's property tax is cut to its own share. Smaller assessments filed the same way cannot be told apart from real overhead and remain in it.\n` : ''}- **Estimated by the Census, not reported (left out, ${imputed.length}):** ${list(imputed)}.${t.imputedNote ? ` ${t.imputedNote}` : ''}
- **Incomplete in the Census files (only debt or a few figures, or spending under a quarter of revenue; left out, ${incomplete.length}):** ${list(incomplete)}.
${report.skipped.length ? `- **No longer a separate government:** ${list(report.skipped.map((s) => s.replace(/: no Census match$/, '')))}${t.skippedNote ? ` (${t.skippedNote})` : ''}.\n` : ''}- **Older year used** because the latest sampled year was estimated or incomplete: ${list(report.older)}.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
  console.log(`docs/${cfg.code}_DATA_STATUS.md: ${towns.length} governments`);
}
