#!/usr/bin/env node
// Writes docs/WA_DATA_STATUS.md from the county files in data/real/ and the last
// `fit-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { FIT_PAGE, FIT_YEARS } from './fit-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'wa', 'fit-report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^wa-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities', Town: 'Towns' };
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  const years = [...new Set(g.map((t) => t.fiscalYear))].sort();
  const fy = years.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
  return { kind, n: g.length, fy, debt: g.filter((t) => typeof t.debt !== 'number').length, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');

writeFileSync(join(ROOT, 'docs', 'WA_DATA_STATUS.md'), `# Washington data status

Generated by \`node scripts/wa/fit-status.mjs\`. ${towns.length} governments loaded. Washington has 39 counties and about 280 cities and towns, and no townships. Counties provide city-type services in unincorporated areas. Public schools, ports, fire, library and public utility districts are separate governments. Each county's file holds the county and the cities and towns whose people mostly live in it.

| Type | Loaded | Fiscal year used (count) | No debt figure | Median score | Median overhead |
|---|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.debt} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue and spending:** each government's annual report to the Washington State Auditor (Schedule 1, by BARS account and fund), from the [Financial Intelligence Tool](${FIT_PAGE})'s full data extracts, fiscal years ${FIT_YEARS[0]}-${FIT_YEARS.at(-1)}. The latest year filed is used; the State Auditor builds each extract about 30 days after the filing deadline, so late filers use an earlier year.
- **Debt:** the extracts carry no debt schedule, so debt outstanding comes from the Census Bureau's individual unit files (\`node scripts/census-debt.mjs --state WA\`), for the latest year each government reported itself; each record says which year.
- **Political money:** the Public Disclosure Commission's open data on data.wa.gov (\`node scripts/wa/fetch-pdc.mjs\`). Cash contributions from businesses, unions and PACs to county, city and town candidates since three years ago are counted, placed by the jurisdiction of the office sought; individuals, candidates' own money, in-kind gifts, and party and caucus committees are not. ${report.withPolitics} governments have political money.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (counties and places).

## How Washington differs
- **Functions come from the report.** Spending is reported by BARS function for every fund: general government, public safety, utilities, transportation, natural and economic environment, social services, and culture and recreation. Capital expenditures (BARS 594) carry their function and count under it when paid. Courts, legal services, planning, economic development, housing and conservation count as overhead.
- **Internal service funds** (equipment rental, self-insurance, information technology) are left out, since the departments they serve report that spending.
- **Borrowing, transfers, interfund loans, refunded debt and depreciation are left out.** Debt service leaves out principal repaid with new borrowing not spent on capital that year (${report.refinanced.length} governments), most likely refinancing.
- **Special districts are separate.** Fire, water, park, library and port districts have their own budgets, so some services residents pay for are not in city or county reports.

## Known gaps
- **Earlier year used:** ${list(report.older)}.
- **Not in the extracts (left out):** Town of Metaline and Town of Washtucna filed no report for ${FIT_YEARS[0]}-${FIT_YEARS.at(-1)} in time for the extracts.${report.skipped.length ? ` No Census match: ${list(report.skipped)}.` : ''}
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/WA_DATA_STATUS.md: ${towns.length} governments`);
