#!/usr/bin/env node
// Writes docs/WI_DATA_STATUS.md from the county files in data/real/ and the last
// `dor-build.mjs --all` report.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { totals, scoreTown } from '../../js/engine/scoring.js';
import { CMRE_YEARS } from './dor-download.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'data', 'real');
const report = JSON.parse(readFileSync(join(ROOT, 'data', 'raw', 'wi', 'dor-report.json'), 'utf8'));
const towns = readdirSync(OUT).filter((f) => /^wi-.*\.json$/.test(f)).flatMap((f) => JSON.parse(readFileSync(join(OUT, f), 'utf8')).towns);
const median = (a) => a.sort((x, y) => x - y)[a.length >> 1];
const label = { County: 'Counties', City: 'Cities', Village: 'Villages', Town: 'Towns' };
const rows = Object.keys(label).map((kind) => {
  const g = towns.filter((t) => t.type === kind);
  const fy = CMRE_YEARS.map((y) => `${y}: ${g.filter((t) => t.fiscalYear === y).length}`).join(', ');
  return { kind, n: g.length, fy, score: g.length && Math.round(median(g.map((t) => scoreTown(t).score))), admin: g.length && Math.round(median(g.map((t) => totals(t).adminShare)) * 100) };
});
const list = (a) => (a.length ? [...new Set(a)].sort().join(', ') : 'none');

writeFileSync(join(ROOT, 'docs', 'WI_DATA_STATUS.md'), `# Wisconsin data status

Generated by \`node scripts/wi/dor-status.mjs\`. ${towns.length} governments loaded. Wisconsin has 72 counties, about 190 cities, 420 villages and 1,240 towns. Towns govern the rural areas outside cities and villages, and cities and villages are separate from the town around them, so each resident has one municipality and one county. Public schools are run by separate school districts. Each county's file holds the county and the governments whose people mostly live in it.

| Type | Loaded | Year used (count) | Median score | Median overhead |
|---|---|---|---|---|
${rows.filter((r) => r.n).map((r) => `| ${label[r.kind]} | ${r.n} | ${r.fy} | ${r.score} | ${r.admin}% |`).join('\n')}

## Sources
- **Revenue, spending and debt:** each government's Municipal Financial Report, compiled by the Wisconsin Department of Revenue as [County and Municipal Revenues and Expenditures](https://www.revenue.wi.gov/Pages/Report/county-municipal-revenues-expenditures.aspx), calendar years ${CMRE_YEARS[0]}-${CMRE_YEARS.at(-1)}. Every county, city, village and town files one; the latest year in balance is used.
- **Population:** U.S. Census Bureau 2025 population estimates. **Map location:** Census 2024 Gazetteer (counties, county subdivisions and places).

## How Wisconsin differs
- **Functions come from the report.** Governmental funds are reported by function (general government, law enforcement, fire, ambulance, highways, sanitation, health and human services, culture, parks, conservation and development, debt service), so services and overhead are as each government reported them. Conservation and development counts as overhead, like general government.
- **Utilities as totals.** Water, sewer, electric and other utility and enterprise funds are reported only as total revenues and expenses, which count as utility charges and utilities.
- **Borrowing and transfers are left out.** Other financing sources and uses (borrowing, transfers between funds and refunding) are not counted as revenue or spending.

## Known gaps
- **Political money is not scored.** Local candidates file campaign finance reports with their municipal clerk, and contributions to county candidates were not loaded.
- **Not filled in (left out, ${report.empty.length}):** ${list(report.empty)}.
- **Revenue and spending more than four times apart in every year (left out, ${report.inconsistent.length}):** ${list(report.inconsistent)}.
- **Earlier year used** because the latest report was out of balance: ${list(report.older)}.
- **No Census geography matched (left out, ${report.skipped.length}):** ${list(report.skipped)}.
- **No residents (left out, ${report.noResidents.length}):** ${list(report.noResidents)}; the Census counts no one living there.
- **Debt** is general obligation debt only; revenue bonds of utilities are not in the compilation.
- **Transparency practices** have not been checked yet, so they are not scored.
`);
console.log(`docs/WI_DATA_STATUS.md: ${towns.length} governments`);
